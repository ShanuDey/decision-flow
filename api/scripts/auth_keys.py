"""Local auth keys: `init` writes a key pair to the untracked .env, `token` signs a test token."""

import json
import sys
import time
from pathlib import Path

import jwt
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from dotenv import dotenv_values

ENV_FILE = Path(__file__).resolve().parents[2] / ".env"
ISSUER = "http://localhost:3000"
AUDIENCE = "decision-flow-api"
TOKEN_LIFETIME_SECONDS = 8 * 3600


def init() -> None:
    values = dotenv_values(ENV_FILE) if ENV_FILE.exists() else {}
    if values.get("AUTH_PROVIDERS"):
        return
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    private = key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    ).decode()
    public = (
        key.public_key()
        .public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo)
        .decode()
    )
    providers = [
        {
            "type": "jwt",
            "name": "web",
            "issuer": ISSUER,
            "audience": AUDIENCE,
            "public_key": public,
        }
    ]
    escaped_private = private.strip().replace("\n", "\\n")
    with ENV_FILE.open("a", encoding="utf-8") as env:
        env.write("\n# generated by `make auth-setup`; local only, never commit\n")
        env.write(f"AUTH_PROVIDERS='{json.dumps(providers)}'\n")
        env.write(f'AUTH_SIGNING_KEY="{escaped_private}"\n')
    print(f"auth: generated a local key pair in {ENV_FILE.name}")


def token(sub: str, email: str | None) -> str:
    values = dotenv_values(ENV_FILE)
    signing_key = (values.get("AUTH_SIGNING_KEY") or "").replace("\\n", "\n")
    if not signing_key:
        raise SystemExit("auth: no AUTH_SIGNING_KEY in .env; run `make auth-setup`")
    provider = json.loads(values["AUTH_PROVIDERS"] or "[]")[0]
    claims = {
        "sub": sub,
        "iss": provider["issuer"],
        "aud": provider["audience"],
        "exp": int(time.time()) + TOKEN_LIFETIME_SECONDS,
    }
    if email:
        claims |= {"email": email, "email_verified": True}
    return jwt.encode(claims, signing_key, algorithm="RS256")


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    if command == "init":
        init()
    elif command == "token":
        print(token(sys.argv[2] if len(sys.argv) > 2 else "local-dev", None))
    else:
        raise SystemExit("usage: auth_keys.py init | token [sub]")
